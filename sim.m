clc;
clear;
close all;

%% Radar Parameters

c = 3e8;              % Speed of light (m/s)

designBW = 2;         % Design bandwidth (MHz)
fs = 10;              % Sampling frequency (MHz)

%% Bandwidth Range

BW_MHz = logspace(-1,2,500);      % 0.1 MHz to 100 MHz
BW = BW_MHz*1e6;

%% Range Resolution

deltaR = c./(2*BW);

%% Design Point

designRes = c/(2*designBW*1e6);

%% Plot

figure('Color','w',...
       'Position',[100 100 920 520]);

hold on
box on
grid on

set(gca,...
    'XScale','log',...
    'FontSize',11,...
    'LineWidth',1);

%% Specification Zone (50–100 m)

hSpec = patch([0.1 100 100 0.1],...
              [50 50 100 100],...
              [0.85 1.00 0.85],...
              'EdgeColor','none',...
              'FaceAlpha',0.35);

%% Range Resolution Curve

hCurve = semilogx(BW_MHz,...
                  deltaR,...
                  'b',...
                  'LineWidth',2);

%% Design Bandwidth

hBW = xline(designBW,...
            '--r',...
            'LineWidth',1.5);

%% Design Resolution

hRes = yline(designRes,...
             '--g',...
             'LineWidth',1.5);

%% Design Point

plot(designBW,...
     designRes,...
     'ro',...
     'MarkerFaceColor','r',...
     'MarkerSize',8);

%% Text Box

text(0.7,900,...
    {sprintf('Design BW = %.0f MHz',designBW),...
     sprintf('\\DeltaR = %.0f m',designRes),...
     'Spec = 50-100 m  OK',...
     sprintf('f_s = %.0f MHz',fs)},...
     'BackgroundColor','white',...
     'EdgeColor',[0.5 0.5 0.5],...
     'Margin',8,...
     'FontSize',10);

%% Labels

xlabel('Bandwidth (MHz)',...
       'FontSize',13,...
       'FontWeight','bold');

ylabel('Range Resolution (m)',...
       'FontSize',13,...
       'FontWeight','bold');

title('Bandwidth vs Range Resolution',...
      'FontSize',15,...
      'FontWeight','bold');

%% Limits

xlim([0.1 100]);
ylim([0 1500]);

%% Legend

legend([hCurve hSpec hBW hRes],...
       {'\DeltaR = c/(2B)',...
        'Spec Zone (50-100 m)',...
        'Design BW',...
        '\DeltaR'},...
       'Location','northeast');

grid minor